#!/usr/bin/env node
// Compile the branded pedal descriptors into lightweight AudioWorklet parameter maps.
// The checked-in output keeps the browser rig runnable without the sibling design repo.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
for (const pedal of [
  { key: 'bloom', id: 'cc.squatch.bloom', keys: 'warmth,bloom,touch,level', symbol: 'BLOOM_PARAMS' },
  { key: 'trail-od', id: 'cc.squatch.trail-od', keys: 'drive,tone,level', symbol: 'TRAIL_OD_PARAMS' },
]) {
  const source = path.resolve(root, `../squatch-skin/contracts/${pedal.key}.params.json`);
  const target = path.join(root, `web/js/graph/${pedal.key}-contract.js`);
  const doc = JSON.parse(fs.readFileSync(source, 'utf8'));
  if (doc.profile !== 'cc.squatch.control/1' || doc.product.id !== pedal.id) throw new Error(`unexpected ${pedal.key} contract`);
  const params = doc.params.filter((p) => p.role === 'param');
  if (params.map((p) => p.key).join(',') !== pedal.keys) throw new Error(`${pedal.key} control order changed`);
  const obj = Object.fromEntries(params.map((p) => [p.key, {
    id: p.id, min: p.min, max: p.max, def: p.default, unit: p.unit === 'db' ? 'dB' : '', label: p.name,
  }]));
  const body = `// Generated by tools/build-bloom-contract.mjs from the shared ${pedal.key} control descriptor.\n`
    + `export const ${pedal.symbol} = Object.freeze(${JSON.stringify(obj, null, 2)});\n`;
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body) {
      console.error(`${pedal.key} AudioWorklet parameter map is stale; run npm run contract:build`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(target, body);
  }
  console.log(`${pedal.key}: ${params.length} shared controls ${process.argv.includes('--check') ? 'checked' : 'generated'}`);
}
